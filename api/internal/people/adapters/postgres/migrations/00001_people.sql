-- Write model: one table per record kind, the record as a JSON document plus the columns the
-- rules and scope filters need. employee_id ties a record to its employee; key is the natural
-- key (an employee's code, a roster or attendance day, a KPI quarter); villa_ids and location_ids
-- carry the scope of employees and announcements. version drives optimistic concurrency and seq
-- keeps creation order, the order the mock's arrays keep.
CREATE TABLE people.employees (
    seq          bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id           text   PRIMARY KEY,
    employee_id  text   NOT NULL DEFAULT '',
    key          text   NOT NULL DEFAULT '',
    villa_ids    text[] NOT NULL DEFAULT '{}',
    location_ids text[] NOT NULL DEFAULT '{}',
    data         jsonb  NOT NULL,
    version      bigint NOT NULL DEFAULT 1
);

