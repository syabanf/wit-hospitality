-- +goose Up
-- The employee area: shift swaps between coworkers, the clock-in radius, and where a villa is so a
-- self clock reads as at the villa or away.

-- Shift swaps: employee_id is the requester, key the shift's day, villa_ids the villa of the shift.
CREATE TABLE people.shift_swaps (
    seq          bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id           text   PRIMARY KEY,
    employee_id  text   NOT NULL DEFAULT '',
    key          text   NOT NULL DEFAULT '',
    villa_ids    text[] NOT NULL DEFAULT '{}',
    location_ids text[] NOT NULL DEFAULT '{}',
    data         jsonb  NOT NULL,
    version      bigint NOT NULL DEFAULT 1
);
CREATE INDEX shift_swaps_open ON people.shift_swaps ((data->>'status'));
CREATE VIEW people.v_shift_swaps AS SELECT seq, id, employee_id, key, villa_ids, location_ids, data FROM people.shift_swaps;

-- Settings of the context, one document per id ('attendance' holds the clock-in radius).
CREATE TABLE people.settings (
    seq          bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id           text   PRIMARY KEY,
    employee_id  text   NOT NULL DEFAULT '',
    key          text   NOT NULL DEFAULT '',
    villa_ids    text[] NOT NULL DEFAULT '{}',
    location_ids text[] NOT NULL DEFAULT '{}',
    data         jsonb  NOT NULL,
    version      bigint NOT NULL DEFAULT 1
);

-- A villa's position from property's villa events. NULL until the copy sees an event that carries
-- it; the snapshot catch-up fills the rows of a database seeded before this migration.
ALTER TABLE people.rm_villas
    ADD COLUMN lat double precision,
    ADD COLUMN lng double precision;

-- Rows written before the clock came from HR's sheet.
UPDATE people.attendance
SET data = data || '{"source": "manual", "corrected": false, "clockInGeo": null, "clockOutGeo": null}'::jsonb
WHERE NOT data ? 'source';

-- +goose Down
UPDATE people.attendance SET data = data - 'source' - 'corrected' - 'clockInGeo' - 'clockOutGeo';
ALTER TABLE people.rm_villas DROP COLUMN lng, DROP COLUMN lat;
DROP TABLE people.settings;
DROP VIEW people.v_shift_swaps;
DROP TABLE people.shift_swaps;
