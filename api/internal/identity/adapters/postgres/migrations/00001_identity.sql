CREATE TABLE identity.users (
    seq              bigint      GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id               text        PRIMARY KEY,
    name             text        NOT NULL,
    email            text        NOT NULL,
    role             text        NOT NULL,
    status           text        NOT NULL CHECK (status IN ('active', 'inactive')),
    location_ids     text[]      NOT NULL DEFAULT '{}',
    villa_ids        text[]      NOT NULL DEFAULT '{}',
    employee_id      text,
    password_hash    text        NOT NULL,
    last_login_on    date,
    created_on       date        NOT NULL,
    notify_arrivals  boolean     NOT NULL DEFAULT true,
    notify_approvals boolean     NOT NULL DEFAULT true,
    version          bigint      NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX users_email ON identity.users (lower(email));

-- One row per role; roles without a row read the default matrix.
CREATE TABLE identity.role_permissions (
    role       text        PRIMARY KEY,
    modules    jsonb       NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE identity.sessions (
    id           text        PRIMARY KEY,
    user_id      text        NOT NULL REFERENCES identity.users (id) ON DELETE CASCADE,
    user_agent   text        NOT NULL DEFAULT '',
    created_at   timestamptz NOT NULL,
    revoked_at   timestamptz
);
CREATE INDEX sessions_user ON identity.sessions (user_id);

CREATE TABLE identity.refresh_tokens (
    id          text        PRIMARY KEY,
    session_id  text        NOT NULL REFERENCES identity.sessions (id) ON DELETE CASCADE,
    user_id     text        NOT NULL,
    token_hash  text        NOT NULL UNIQUE,
    expires_at  timestamptz NOT NULL,
    rotated_at  timestamptz,
    replaced_by text,
    revoked_at  timestamptz
);
CREATE INDEX refresh_tokens_session ON identity.refresh_tokens (session_id);

-- Read model: the audit trail, projected from platform.audit.recorded.v1 events of every context.
CREATE TABLE identity.audit_trail (
    seq       bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id        text   PRIMARY KEY,
    at        text   NOT NULL,
    user_id   text   NOT NULL,
    user_name text   NOT NULL,
    role      text   NOT NULL,
    action    text   NOT NULL,
    entity    text   NOT NULL,
    entity_id text   NOT NULL,
    summary   text   NOT NULL,
    before    jsonb,
    after     jsonb
);
CREATE INDEX audit_trail_at ON identity.audit_trail (at DESC, seq DESC);

-- Read models served straight from the write tables, without secrets.
CREATE VIEW identity.v_users AS
SELECT seq, id, name, email, role, status, location_ids, villa_ids, employee_id,
       to_char(last_login_on, 'YYYY-MM-DD') AS last_login_on,
       to_char(created_on, 'YYYY-MM-DD')    AS created_on,
       notify_arrivals, notify_approvals
FROM identity.users;

CREATE VIEW identity.v_permissions AS
SELECT role, modules FROM identity.role_permissions;

