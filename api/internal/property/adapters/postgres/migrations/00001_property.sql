-- Write model: one table per aggregate, version for optimistic concurrency.
CREATE TABLE property.locations (
    id      text   PRIMARY KEY,
    name    text   NOT NULL,
    area    text   NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

CREATE TABLE property.villas (
    id          text   PRIMARY KEY,
    location_id text   NOT NULL REFERENCES property.locations (id),
    code        text   NOT NULL UNIQUE,
    name        text   NOT NULL,
    description text   NOT NULL DEFAULT '',
    facilities  text[] NOT NULL DEFAULT '{}',
    version     bigint NOT NULL DEFAULT 1
);

CREATE TABLE property.unit_groups (
    id               text    PRIMARY KEY,
    villa_id         text    NOT NULL REFERENCES property.villas (id),
    name             text    NOT NULL,
    interchangeable  boolean NOT NULL,
    operator_assigns boolean NOT NULL,
    version          bigint  NOT NULL DEFAULT 1,
    CHECK (NOT operator_assigns OR interchangeable)
);

CREATE TABLE property.units (
    id           text    PRIMARY KEY,
    villa_id     text    NOT NULL REFERENCES property.villas (id),
    group_id     text    REFERENCES property.unit_groups (id),
    code         text    NOT NULL UNIQUE,
    name         text    NOT NULL,
    bedrooms     integer NOT NULL CHECK (bedrooms >= 1),
    nightly_rate bigint  NOT NULL CHECK (nightly_rate > 0),
    status       text    NOT NULL CHECK (status IN ('active', 'cleaning', 'maintenance', 'inactive')),
    amenities    text[]  NOT NULL DEFAULT '{}',
    version      bigint  NOT NULL DEFAULT 1
);

CREATE TABLE property.rate_plans (
    group_id     text   PRIMARY KEY REFERENCES property.unit_groups (id),
    weekday_rate bigint NOT NULL CHECK (weekday_rate > 0),
    weekend_rate bigint NOT NULL CHECK (weekend_rate > 0),
    seasons      jsonb  NOT NULL DEFAULT '[]'::jsonb,
    version      bigint NOT NULL DEFAULT 1
);

CREATE TABLE property.unit_blocks (
    id        text PRIMARY KEY,
    unit_id   text NOT NULL REFERENCES property.units (id),
    from_date date NOT NULL,
    to_date   date NOT NULL CHECK (to_date > from_date),
    reason    text NOT NULL,
    note      text NOT NULL DEFAULT ''
);

-- Read models, kept by the projector from property events. Each row carries the villa and
-- location it sits in, so scope filters need no joins. seq keeps creation order; version drops
-- an older event that arrives late.
CREATE TABLE property.rm_locations (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    name    text   NOT NULL,
    area    text   NOT NULL,
    version bigint NOT NULL
);

