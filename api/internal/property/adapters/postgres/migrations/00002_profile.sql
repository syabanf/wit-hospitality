-- Every status change from any source: a user's edit, housekeeping or a maintenance work order.
-- on_date is the business day of the change, which the history filters on.
CREATE TABLE property.unit_status_history (
    seq         bigint      GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          text        PRIMARY KEY,
    unit_id     text        NOT NULL REFERENCES property.units (id),
    villa_id    text        NOT NULL,
    location_id text        NOT NULL,
    from_status text        NOT NULL,
    to_status   text        NOT NULL,
    reason      text        NOT NULL,
    until       date,
    by_name     text        NOT NULL,
    at          timestamptz NOT NULL,
    on_date     date        NOT NULL
);
CREATE INDEX unit_status_history_unit ON property.unit_status_history (unit_id, seq);

