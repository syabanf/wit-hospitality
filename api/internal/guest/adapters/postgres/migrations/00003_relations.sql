-- Guest relations: complaints, incidents, safe deposit boxes and the boxes opened for stays. Each
-- row keeps the record in doc next to the columns the rules and the scope filter look up.
CREATE TABLE guest.complaints (
    seq        bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id         text   PRIMARY KEY,
    number     text   NOT NULL UNIQUE,
    villa_id   text   NOT NULL,
    guest_id   text   NOT NULL,
    booking_id text,
    doc        jsonb  NOT NULL,
    version    bigint NOT NULL DEFAULT 1
);
CREATE INDEX complaints_guest ON guest.complaints (guest_id);

CREATE TABLE guest.incidents (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id       text   PRIMARY KEY,
    number   text   NOT NULL UNIQUE,
    villa_id text   NOT NULL,
    doc      jsonb  NOT NULL,
    version  bigint NOT NULL DEFAULT 1
);

CREATE TABLE guest.safe_boxes (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id       text   PRIMARY KEY,
    villa_id text   NOT NULL,
    doc      jsonb  NOT NULL,
    version  bigint NOT NULL DEFAULT 1
);

CREATE TABLE guest.box_rentals (
    seq        bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id         text   PRIMARY KEY,
    number     text   NOT NULL UNIQUE,
    box_id     text   NOT NULL,
    villa_id   text   NOT NULL,
    booking_id text   NOT NULL,
    guest_id   text   NOT NULL,
    doc        jsonb  NOT NULL,
    version    bigint NOT NULL DEFAULT 1
);
CREATE INDEX box_rentals_guest ON guest.box_rentals (guest_id);

CREATE VIEW guest.v_complaints AS
    SELECT c.seq, c.id, c.doc, c.villa_id, v.location_id
    FROM guest.complaints c LEFT JOIN guest.rm_villas v ON v.id = c.villa_id;

CREATE VIEW guest.v_incidents AS
    SELECT i.seq, i.id, i.doc, i.villa_id, v.location_id
    FROM guest.incidents i LEFT JOIN guest.rm_villas v ON v.id = i.villa_id;

CREATE VIEW guest.v_safe_boxes AS
    SELECT b.seq, b.id, b.doc, b.villa_id, v.location_id
    FROM guest.safe_boxes b LEFT JOIN guest.rm_villas v ON v.id = b.villa_id;

CREATE VIEW guest.v_box_rentals AS
    SELECT r.seq, r.id, r.doc, r.villa_id, v.location_id
    FROM guest.box_rentals r LEFT JOIN guest.rm_villas v ON v.id = r.villa_id;

