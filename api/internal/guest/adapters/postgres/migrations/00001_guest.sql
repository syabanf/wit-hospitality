-- Write model. Each aggregate keeps its full state in doc (the JSON the console reads) next to
-- the columns the rules look up; version is the optimistic concurrency check. seq keeps creation
-- order, as the mock's arrays do.
CREATE TABLE guest.guests (
    seq       bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id        text   PRIMARY KEY,
    name      text   NOT NULL,
    doc       jsonb  NOT NULL,
    version   bigint NOT NULL DEFAULT 1
);

CREATE TABLE guest.companions (
    seq        bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id         text   PRIMARY KEY,
    booking_id text   NOT NULL,
    doc        jsonb  NOT NULL,
    version    bigint NOT NULL DEFAULT 1
);
CREATE INDEX companions_booking ON guest.companions (booking_id);

CREATE TABLE guest.foreign_reports (
    seq         bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          text PRIMARY KEY,
    booking_id  text NOT NULL,
    person_id   text NOT NULL,
    reported_at text NOT NULL,
    reported_by text NOT NULL,
    reference   text NOT NULL DEFAULT '',
    UNIQUE (booking_id, person_id)
);

CREATE TABLE guest.lost_items (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id       text   PRIMARY KEY,
    number   text   NOT NULL UNIQUE,
    villa_id text   NOT NULL,
    guest_id text,
    doc      jsonb  NOT NULL,
    version  bigint NOT NULL DEFAULT 1
);

-- Settings by key (lost-found: { holdDays }).
CREATE TABLE guest.settings (
    key     text   PRIMARY KEY,
    value   jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

-- The mock's seq(): the next number per kind of record (guest, companion, foreignReport, lostItem).
CREATE TABLE guest.counters (
    key  text   PRIMARY KEY,
    next bigint NOT NULL
);

-- What guest knows of other contexts, kept in its own schema. Property events feed the villa,
-- unit and location rows. Stays and group leads come from the seed until the reservation context
-- publishes booking events; see docs/ARCHITECTURE.md, guest context.
CREATE TABLE guest.rm_locations (
    id      text   PRIMARY KEY,
    name    text   NOT NULL,
    area    text   NOT NULL,
    version bigint NOT NULL
);

CREATE TABLE guest.rm_villas (
    id          text   PRIMARY KEY,
    location_id text   NOT NULL,
    name        text   NOT NULL,
    version     bigint NOT NULL
);

CREATE TABLE guest.rm_units (
    id       text   PRIMARY KEY,
    villa_id text   NOT NULL,
    code     text   NOT NULL,
    version  bigint NOT NULL
);

CREATE TABLE guest.rm_stays (
    seq            bigint  GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id             text    PRIMARY KEY,
    code           text    NOT NULL,
    guest_id       text    NOT NULL,
    unit_id        text    NOT NULL,
    villa_id       text    NOT NULL,
    status         text    NOT NULL,
    check_in       text    NOT NULL,
    check_out      text    NOT NULL,
    checked_in_on  text,
    checked_out_on text,
    arrival_time   text    NOT NULL DEFAULT '',
    adults         integer,
    version        bigint  NOT NULL DEFAULT 1
);
CREATE INDEX rm_stays_guest ON guest.rm_stays (guest_id);

CREATE TABLE guest.rm_group_leads (
    id            text   PRIMARY KEY,
    lead_guest_id text   NOT NULL,
    version       bigint NOT NULL DEFAULT 1
);

-- Read views. Each row carries the villa and location it sits in for the scope filter.
CREATE VIEW guest.v_guests AS
    SELECT seq, id, doc FROM guest.guests;

CREATE VIEW guest.v_companions AS
    SELECT c.seq, c.id, c.booking_id, c.doc, s.villa_id, v.location_id
    FROM guest.companions c
    LEFT JOIN guest.rm_stays s ON s.id = c.booking_id
    LEFT JOIN guest.rm_villas v ON v.id = s.villa_id;

CREATE VIEW guest.v_foreign_reports AS
    SELECT r.seq, r.id, r.booking_id, r.person_id, r.reported_at, r.reported_by, r.reference, s.villa_id, v.location_id
    FROM guest.foreign_reports r
    LEFT JOIN guest.rm_stays s ON s.id = r.booking_id
    LEFT JOIN guest.rm_villas v ON v.id = s.villa_id;

CREATE VIEW guest.v_lost_items AS
    SELECT l.seq, l.id, l.doc, l.villa_id, v.location_id
    FROM guest.lost_items l
    LEFT JOIN guest.rm_villas v ON v.id = l.villa_id;

CREATE VIEW guest.v_stays AS
    SELECT s.*, v.location_id, v.name AS villa_name, loc.name AS location_name, loc.area AS location_area, u.code AS unit_code
    FROM guest.rm_stays s
    LEFT JOIN guest.rm_villas v ON v.id = s.villa_id
    LEFT JOIN guest.rm_locations loc ON loc.id = v.location_id
    LEFT JOIN guest.rm_units u ON u.id = s.unit_id;

