-- Write model. A message keeps the console's JSON in doc beside the columns the triggers, the
-- sweep and the scope filter look up; reads come straight from it.
CREATE TABLE messaging.counters (
    key text   PRIMARY KEY,
    n   bigint NOT NULL
);

CREATE TABLE messaging.settings (
    id      text   PRIMARY KEY,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

CREATE TABLE messaging.messages (
    seq          bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id           text   PRIMARY KEY,
    booking_id   text   NOT NULL,
    guest_id     text   NOT NULL,
    villa_id     text   NOT NULL,
    template_key text,
    system       boolean NOT NULL,
    status       text   NOT NULL,
    doc          jsonb  NOT NULL,
    version      bigint NOT NULL DEFAULT 1
);
CREATE INDEX messages_booking ON messaging.messages (booking_id, template_key);
CREATE INDEX messages_status ON messaging.messages (status);

-- Copies of other contexts' records, kept by the projector: the catalog (messaging.catalog), guest
-- contacts (messaging.guest), stays (messaging.reservation) and payment links (messaging.billing).
CREATE TABLE messaging.cat_villas (
    id          text   PRIMARY KEY,
    location_id text   NOT NULL,
    name        text   NOT NULL,
    version     bigint NOT NULL
);

CREATE TABLE messaging.cat_unit_groups (
    id      text   PRIMARY KEY,
    name    text   NOT NULL,
    version bigint NOT NULL
);

CREATE TABLE messaging.cat_units (
    id       text   PRIMARY KEY,
    villa_id text   NOT NULL,
    group_id text,
    code     text   NOT NULL,
    version  bigint NOT NULL
);

CREATE TABLE messaging.guests (
    id          text   PRIMARY KEY,
    name        text   NOT NULL,
    email       text   NOT NULL,
    phone       text   NOT NULL,
    nationality text   NOT NULL,
    version     bigint NOT NULL
);

CREATE TABLE messaging.stays (
    seq           bigint  GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id            text    PRIMARY KEY,
    code          text    NOT NULL,
    guest_id      text    NOT NULL,
    unit_id       text    NOT NULL,
    unit_assigned boolean NOT NULL,
    status        text    NOT NULL,
    check_in      date    NOT NULL,
    check_out     date    NOT NULL,
    group_id      text    NOT NULL DEFAULT '',
    invoice_token text    NOT NULL UNIQUE,
    version       bigint  NOT NULL
);

CREATE TABLE messaging.payment_links (
    seq        bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    token      text   PRIMARY KEY,
    booking_id text   NOT NULL,
    amount     bigint NOT NULL,
    status     text   NOT NULL,
    version    bigint NOT NULL
);
CREATE INDEX payment_links_booking ON messaging.payment_links (booking_id);

