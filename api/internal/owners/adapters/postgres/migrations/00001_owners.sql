-- +goose Up
-- Write model. Each record keeps the console's JSON in doc; the columns beside it are what the
-- rules and the scope filters look up. Reads come from these tables directly.
CREATE TABLE owners.counters (
    key text   PRIMARY KEY,
    n   bigint NOT NULL
);

CREATE TABLE owners.villa_owners (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    user_id text,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

CREATE TABLE owners.contracts (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id       text   PRIMARY KEY,
    villa_id text   NOT NULL,
    owner_id text   NOT NULL,
    doc      jsonb  NOT NULL,
    version  bigint NOT NULL DEFAULT 1
);

-- payout_* follow the cash entry finance makes for the statement (owners.payout.requested and
-- finance.entry.* keyed by payout_ref).
CREATE TABLE owners.statements (
    seq           bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id            text   PRIMARY KEY,
    contract_id   text   NOT NULL,
    villa_id      text   NOT NULL,
    owner_id      text   NOT NULL,
    month         text   NOT NULL,
    status        text   NOT NULL CHECK (status IN ('closed', 'approved')),
    doc           jsonb  NOT NULL,
    payout_ref    text UNIQUE,
    payout_number text   NOT NULL DEFAULT '',
    payout_status text   NOT NULL DEFAULT '',
    version       bigint NOT NULL DEFAULT 1,
    UNIQUE (contract_id, month)
);

CREATE TABLE owners.stay_requests (
    seq         bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          text   PRIMARY KEY,
    contract_id text   NOT NULL,
    villa_id    text   NOT NULL,
    owner_id    text   NOT NULL,
    doc         jsonb  NOT NULL,
    version     bigint NOT NULL DEFAULT 1
);

-- Copies of other contexts' records, kept from their events.
CREATE TABLE owners.cat_locations (
    id      text   PRIMARY KEY,
    name    text   NOT NULL,
    version bigint NOT NULL
);

CREATE TABLE owners.cat_villas (
    seq         bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          text   PRIMARY KEY,
    location_id text   NOT NULL,
    code        text   NOT NULL,
    name        text   NOT NULL,
    version     bigint NOT NULL
);

CREATE TABLE owners.cat_units (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id       text   PRIMARY KEY,
    villa_id text   NOT NULL,
    code     text   NOT NULL,
    status   text   NOT NULL,
    version  bigint NOT NULL
);

CREATE TABLE owners.cat_blocks (
    id        text    PRIMARY KEY,
    unit_id   text    NOT NULL,
    from_date text    NOT NULL,
    to_date   text    NOT NULL,
    reason    text    NOT NULL,
    removed   boolean NOT NULL DEFAULT false,
    version   bigint  NOT NULL
);

CREATE TABLE owners.cat_accounts (
    id      text   PRIMARY KEY,
    name    text   NOT NULL,
    version bigint NOT NULL
);

-- Reservation's bookings, whole, from booking.saved and booking.status_changed.
CREATE TABLE owners.rm_stays (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    unit_id text   NOT NULL,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL
);
CREATE INDEX rm_stays_unit ON owners.rm_stays (unit_id);

