-- Write model. Each record keeps the console's JSON shape in doc; the columns beside it are what
-- the rules, the scope filters and the locks look up. Commands lock a row with SELECT ... FOR
-- UPDATE inside their transaction and bump version on every change.
CREATE TABLE finance.counters (
    key text   PRIMARY KEY,
    n   bigint NOT NULL
);

CREATE TABLE finance.cash_accounts (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

CREATE TABLE finance.categories (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

-- source_type and source_id name the record another context asked the entry for (a payment, an
-- expense, a stock purchase, a payroll, a walk); the finance client answers by them.
CREATE TABLE finance.transactions (
    seq         bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          text   PRIMARY KEY,
    number      text   NOT NULL UNIQUE,
    account_id  text   NOT NULL,
    status      text   NOT NULL CHECK (status IN ('draft', 'submitted', 'approved', 'posted', 'rejected', 'reversed')),
    date        date   NOT NULL,
    transfer_id text,
    source_type text,
    source_id   text,
    doc         jsonb  NOT NULL,
    version     bigint NOT NULL DEFAULT 1
);
CREATE INDEX transactions_transfer ON finance.transactions (transfer_id);
CREATE INDEX transactions_source ON finance.transactions (source_type, source_id);

-- What the posting rules read about an entry from the context that asked for it.
CREATE TABLE finance.entry_links (
    transaction_id text  PRIMARY KEY,
    doc            jsonb NOT NULL
);

CREATE TABLE finance.payroll_postings (
    transaction_id text  PRIMARY KEY,
    doc            jsonb NOT NULL
);

CREATE TABLE finance.reconciliations (
    seq bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id  text   PRIMARY KEY,
    doc jsonb  NOT NULL
);

CREATE TABLE finance.approval_rules (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

-- proof_policy, tax, shift_policy, category_accounts.
CREATE TABLE finance.settings (
    key     text   PRIMARY KEY,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

CREATE TABLE finance.transaction_codes (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

-- Journal entries are written once and never edited.
CREATE TABLE finance.journals (
    seq       bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id        text   PRIMARY KEY,
    date      date   NOT NULL,
    source    text   NOT NULL,
    source_id text   NOT NULL,
    villa_id  text,
    doc       jsonb  NOT NULL
);
CREATE INDEX journals_source ON finance.journals (source, source_id);

CREATE TABLE finance.manual_journals (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

CREATE TABLE finance.period_closes (
    month text  PRIMARY KEY,
    doc   jsonb NOT NULL
);

CREATE TABLE finance.budgets (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    villa_id text   NOT NULL,
    year     int    NOT NULL,
    doc      jsonb  NOT NULL,
    PRIMARY KEY (villa_id, year)
);

CREATE TABLE finance.cashier_shifts (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

CREATE TABLE finance.hand_overs (
    seq bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id  text   PRIMARY KEY,
    doc jsonb  NOT NULL
);

-- What finance knows of other contexts, kept from their events: each stay's state and first
-- billed day (consumers finance.reservation and finance.billing), and the villas and locations
-- that scope the ledger (consumer finance.catalog).
CREATE TABLE finance.stays (
    booking_id text   PRIMARY KEY,
    doc        jsonb  NOT NULL,
    version    bigint NOT NULL DEFAULT 0
);

CREATE TABLE finance.cat_locations (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    name    text   NOT NULL,
    area    text   NOT NULL,
    version bigint NOT NULL
);

CREATE TABLE finance.cat_villas (
    seq         bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          text   PRIMARY KEY,
    location_id text   NOT NULL,
    name        text   NOT NULL,
    version     bigint NOT NULL
);

-- Who works a shift on which day, from people's roster (consumer finance.people): a cashier
-- opens a drawer on a day they are rostered.
CREATE TABLE finance.roster (
    id          text    PRIMARY KEY,
    employee_id text    NOT NULL,
    date        text    NOT NULL,
    on_shift    boolean NOT NULL,
    version     bigint  NOT NULL
);
CREATE INDEX roster_employee_date ON finance.roster (employee_id, date);

