-- Write model. A booking, group, restriction, walk and pre-check-in keep the console's JSON shape
-- in doc; the columns beside it are what availability, the stays client and the locks query.
CREATE TABLE reservation.counters (
    key text   PRIMARY KEY,
    n   bigint NOT NULL
);

CREATE TABLE reservation.bookings (
    seq           bigint  GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id            text    PRIMARY KEY,
    code          text    NOT NULL UNIQUE,
    unit_id       text    NOT NULL,
    unit_assigned boolean NOT NULL,
    status        text    NOT NULL CHECK (status IN ('draft', 'confirmed', 'checked_in', 'checked_out', 'cancelled', 'no_show')),
    check_in      date    NOT NULL,
    check_out     date    NOT NULL CHECK (check_out > check_in),
    group_id      text,
    checkin_token text    NOT NULL UNIQUE,
    doc           jsonb   NOT NULL,
    version       bigint  NOT NULL DEFAULT 1
);
CREATE INDEX bookings_unit_dates ON reservation.bookings (unit_id, check_in, check_out);
CREATE INDEX bookings_group ON reservation.bookings (group_id);

CREATE TABLE reservation.booking_groups (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    code    text   NOT NULL UNIQUE,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

CREATE TABLE reservation.restrictions (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id       text   PRIMARY KEY,
    group_id text   NOT NULL,
    doc      jsonb  NOT NULL,
    version  bigint NOT NULL DEFAULT 1
);

CREATE TABLE reservation.overbooking (
    seq      bigint  GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    group_id text    PRIMARY KEY,
    lim      integer NOT NULL CHECK (lim BETWEEN 0 AND 5),
    version  bigint  NOT NULL DEFAULT 1
);

CREATE TABLE reservation.walks (
    seq        bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id         text   PRIMARY KEY,
    booking_id text   NOT NULL,
    doc        jsonb  NOT NULL
);

CREATE TABLE reservation.pre_checkins (
    seq        bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    booking_id text   PRIMARY KEY,
    doc        jsonb  NOT NULL,
    version    bigint NOT NULL DEFAULT 1
);

-- The property catalog as reservation sees it, kept from property events by the
-- reservation.catalog consumer. Availability and pricing read these, never the property schema.
CREATE TABLE reservation.cat_locations (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    name    text   NOT NULL,
    version bigint NOT NULL
);

CREATE TABLE reservation.cat_villas (
    seq         bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          text   PRIMARY KEY,
    location_id text   NOT NULL,
    name        text   NOT NULL,
    version     bigint NOT NULL
);

CREATE TABLE reservation.cat_unit_groups (
    seq              bigint  GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id               text    PRIMARY KEY,
    villa_id         text    NOT NULL,
    name             text    NOT NULL,
    interchangeable  boolean NOT NULL,
    operator_assigns boolean NOT NULL,
    version          bigint  NOT NULL
);

CREATE TABLE reservation.cat_units (
    seq          bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id           text   PRIMARY KEY,
    villa_id     text   NOT NULL,
    group_id     text,
    code         text   NOT NULL,
    name         text   NOT NULL,
    nightly_rate bigint NOT NULL,
    status       text   NOT NULL,
    version      bigint NOT NULL
);

CREATE TABLE reservation.cat_rate_plans (
    group_id text   PRIMARY KEY,
    plan     jsonb  NOT NULL,
    version  bigint NOT NULL
);

CREATE TABLE reservation.cat_blocks (
    id        text    PRIMARY KEY,
    unit_id   text    NOT NULL,
    from_date text    NOT NULL,
    to_date   text    NOT NULL,
    reason    text    NOT NULL,
    removed   boolean NOT NULL DEFAULT false,
    version   bigint  NOT NULL
);

-- Read models, kept by the reservation.read-model consumer from reservation events. Each row
-- carries the villas and locations it sits in (a group may span several), so scope filters need
-- no join. seq keeps creation order; version drops an older event that arrives late.
CREATE TABLE reservation.rm_bookings (
    seq          bigint  GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id           text    PRIMARY KEY,
    villa_ids    text[]  NOT NULL,
    location_ids text[]  NOT NULL,
    doc          jsonb   NOT NULL,
    removed      boolean NOT NULL DEFAULT false,
    version      bigint  NOT NULL
);
CREATE TABLE reservation.rm_booking_groups (LIKE reservation.rm_bookings INCLUDING ALL);
CREATE TABLE reservation.rm_restrictions (LIKE reservation.rm_bookings INCLUDING ALL);
CREATE TABLE reservation.rm_overbooking (LIKE reservation.rm_bookings INCLUDING ALL);
CREATE TABLE reservation.rm_walks (LIKE reservation.rm_bookings INCLUDING ALL);
CREATE TABLE reservation.rm_pre_checkins (LIKE reservation.rm_bookings INCLUDING ALL);

