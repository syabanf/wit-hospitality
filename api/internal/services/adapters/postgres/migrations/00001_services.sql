-- +goose Up
-- Write model. Each row keeps the console's JSON in doc beside the columns the scope filter and the
-- rules look up, with version for optimistic concurrency. Reads go straight to these tables, so a
-- saved order is on the board at once.
CREATE TABLE services.counters (
    key text   PRIMARY KEY,
    n   bigint NOT NULL
);

CREATE TABLE services.partners (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

CREATE TABLE services.menu_items (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id       text   PRIMARY KEY,
    villa_id text   NOT NULL,
    doc      jsonb  NOT NULL,
    version  bigint NOT NULL DEFAULT 1
);
CREATE INDEX menu_items_villa ON services.menu_items (villa_id);

CREATE TABLE services.orders (
    seq        bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id         text   PRIMARY KEY,
    booking_id text   NOT NULL,
    villa_id   text   NOT NULL,
    doc        jsonb  NOT NULL,
    version    bigint NOT NULL DEFAULT 1
);
CREATE INDEX orders_booking ON services.orders (booking_id);
CREATE INDEX orders_villa ON services.orders (villa_id);

CREATE TABLE services.requests (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id       text   PRIMARY KEY,
    unit_id  text   NOT NULL,
    villa_id text   NOT NULL,
    doc      jsonb  NOT NULL,
    version  bigint NOT NULL DEFAULT 1
);
CREATE INDEX requests_villa ON services.requests (villa_id);

-- The property catalog as services sees it, kept from property events by the services.catalog
-- consumer: villas for the menu and the scope filter, units for requests and the QR cards.
CREATE TABLE services.cat_locations (
    id      text   PRIMARY KEY,
    name    text   NOT NULL,
    version bigint NOT NULL
);

CREATE TABLE services.cat_villas (
    seq         bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          text   PRIMARY KEY,
    location_id text   NOT NULL,
    name        text   NOT NULL,
    version     bigint NOT NULL
);

CREATE TABLE services.cat_units (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id       text   PRIMARY KEY,
    villa_id text   NOT NULL,
    code     text   NOT NULL,
    name     text   NOT NULL,
    status   text   NOT NULL,
    version  bigint NOT NULL
);

