-- +goose Up
-- Write model. Tasks, board records, pars and batches keep the console's JSON shape in doc; the
-- columns beside it are what the commands and the scope filter look up. version guards concurrent
-- saves. Reads come straight from these tables, so a save is visible at once.
CREATE TABLE housekeeping.counters (
    key text   PRIMARY KEY,
    n   bigint NOT NULL
);

CREATE TABLE housekeeping.settings (
    id      text   PRIMARY KEY,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

CREATE TABLE housekeeping.board (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    unit_id  text   PRIMARY KEY,
    villa_id text   NOT NULL,
    state    text   NOT NULL CHECK (state IN ('dirty', 'cleaning', 'inspected', 'ready', 'out_of_order')),
    doc      jsonb  NOT NULL,
    version  bigint NOT NULL DEFAULT 1
);

CREATE TABLE housekeeping.tasks (
    seq          bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id           text   PRIMARY KEY,
    day          date   NOT NULL,
    villa_id     text   NOT NULL,
    unit_id      text   NOT NULL,
    status       text   NOT NULL,
    attendant_id text,
    doc          jsonb  NOT NULL,
    version      bigint NOT NULL DEFAULT 1
);
CREATE INDEX tasks_day ON housekeeping.tasks (day);

CREATE TABLE housekeeping.linen_pars (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    group_id text   PRIMARY KEY,
    villa_id text   NOT NULL,
    doc      jsonb  NOT NULL,
    version  bigint NOT NULL DEFAULT 1
);

CREATE TABLE housekeeping.linen_soiled (
    seq      bigint  GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    villa_id text    NOT NULL,
    item_id  text    NOT NULL,
    quantity integer NOT NULL,
    PRIMARY KEY (villa_id, item_id)
);

CREATE TABLE housekeeping.laundry_batches (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id       text   PRIMARY KEY,
    villa_id text   NOT NULL,
    status   text   NOT NULL CHECK (status IN ('out', 'returned')),
    doc      jsonb  NOT NULL,
    version  bigint NOT NULL DEFAULT 1
);

-- Copies of other contexts' records, kept by the projector: the catalog from property events
-- (consumer housekeeping.catalog) and the stays from reservation events (housekeeping.reservation).
CREATE TABLE housekeeping.cat_villas (
    seq         bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          text   PRIMARY KEY,
    location_id text   NOT NULL,
    name        text   NOT NULL,
    version     bigint NOT NULL
);

CREATE TABLE housekeeping.cat_unit_groups (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id       text   PRIMARY KEY,
    villa_id text   NOT NULL,
    name     text   NOT NULL,
    version  bigint NOT NULL
);

CREATE TABLE housekeeping.cat_units (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id       text   PRIMARY KEY,
    villa_id text   NOT NULL,
    group_id text,
    code     text   NOT NULL,
    status   text   NOT NULL,
    version  bigint NOT NULL
);

CREATE TABLE housekeeping.stays (
    seq           bigint  GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id            text    PRIMARY KEY,
    code          text    NOT NULL,
    unit_id       text    NOT NULL,
    unit_assigned boolean NOT NULL,
    status        text    NOT NULL,
    check_in      date    NOT NULL,
    check_out     date    NOT NULL,
    version       bigint  NOT NULL
);
CREATE INDEX stays_unit ON housekeeping.stays (unit_id);

