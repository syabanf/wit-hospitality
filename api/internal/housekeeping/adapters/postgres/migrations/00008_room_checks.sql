-- +goose Up
-- Housekeeping's room report: one check per room per day with what housekeeping found, the front
-- office side when it was saved, and how the desk resolved a discrepancy. The stays copy gains the
-- party in the room; NULL means the copy has not seen an event since, and the snapshot catch-up
-- fills those rows at the same version.
CREATE TABLE housekeeping.room_checks (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id       text   PRIMARY KEY,
    unit_id  text   NOT NULL,
    villa_id text   NOT NULL,
    date     date   NOT NULL,
    doc      jsonb  NOT NULL,
    version  bigint NOT NULL DEFAULT 1
);
CREATE INDEX room_checks_date ON housekeeping.room_checks (date);

