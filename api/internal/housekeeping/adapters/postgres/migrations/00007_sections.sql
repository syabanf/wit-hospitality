-- +goose Up
-- Sections group a hotel's rooms (property owns them). Housekeeping keeps a copy from
-- property.section.saved.v1 and property.section.removed.v1 (consumer housekeeping.catalog) and
-- gives a section to one attendant per day; a task made later for a room of the section that day
-- starts with that attendant.
CREATE TABLE housekeeping.cat_sections (
    seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id       text   PRIMARY KEY,
    villa_id text   NOT NULL,
    name     text   NOT NULL,
    unit_ids jsonb  NOT NULL DEFAULT '[]',
    version  bigint NOT NULL
);

CREATE TABLE housekeeping.section_assignments (
    section_id   text NOT NULL,
    date         date NOT NULL,
    attendant_id text NOT NULL,
    PRIMARY KEY (section_id, date)
);

-- +goose Down
DROP TABLE housekeeping.section_assignments;
DROP TABLE housekeeping.cat_sections;
