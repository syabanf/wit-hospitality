-- +goose Up
-- Housekeeping's copy of the people it gives rooms to, kept from people events by the
-- housekeeping.people consumer: employees, the roster and leave requests.
CREATE TABLE housekeeping.staff_employees (
    seq        bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id         text   PRIMARY KEY,
    name       text   NOT NULL,
    department text   NOT NULL,
    position   text   NOT NULL,
    status     text   NOT NULL,
    villa_ids  text[] NOT NULL,
    version    bigint NOT NULL
);

CREATE TABLE housekeeping.staff_roster (
    id          text   PRIMARY KEY,
    employee_id text   NOT NULL,
    day         date   NOT NULL,
    shift_id    text,
    villa_id    text   NOT NULL,
    version     bigint NOT NULL
);
CREATE INDEX staff_roster_day ON housekeeping.staff_roster (day);

CREATE TABLE housekeeping.staff_leaves (
    id          text   PRIMARY KEY,
    employee_id text   NOT NULL,
    status      text   NOT NULL,
    from_day    date   NOT NULL,
    to_day      date   NOT NULL,
    version     bigint NOT NULL
);

-- +goose Down
DROP TABLE housekeeping.staff_leaves;
DROP TABLE housekeeping.staff_roster;
DROP TABLE housekeeping.staff_employees;
