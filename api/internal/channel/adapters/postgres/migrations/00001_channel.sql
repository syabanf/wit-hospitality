-- +goose Up
-- Write model: one table per aggregate, version for optimistic concurrency, seq for list order.
CREATE TABLE channel.airbnb_accounts (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    name    text   NOT NULL,
    email   text   NOT NULL,
    status  text   NOT NULL CHECK (status IN ('active', 'paused')),
    slot    integer NOT NULL,
    version bigint NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX airbnb_accounts_name ON channel.airbnb_accounts (lower(name));

-- One listing per unit and one per Airbnb id; date_rates maps a night to its rupiah price.
CREATE TABLE channel.listings (
    seq        bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id         text   PRIMARY KEY,
    account_id text   NOT NULL REFERENCES channel.airbnb_accounts (id),
    unit_id    text   NOT NULL UNIQUE,
    title      text   NOT NULL,
    airbnb_id  text   NOT NULL UNIQUE,
    status     text   NOT NULL CHECK (status IN ('active', 'paused')),
    date_rates jsonb  NOT NULL DEFAULT '{}'::jsonb,
    version    bigint NOT NULL DEFAULT 1
);

-- Web enquiries. pos orders the list newest first; the number comes from enquiry_seq.
CREATE SEQUENCE channel.enquiry_seq;
CREATE TABLE channel.enquiries (
    seq         bigint  PRIMARY KEY,
    id          text    NOT NULL UNIQUE,
    number      text    NOT NULL UNIQUE,
    pos         bigint  NOT NULL,
    topic       text    NOT NULL DEFAULT '',
    name        text    NOT NULL,
    email       text    NOT NULL,
    whatsapp    text    NOT NULL,
    country     text    NOT NULL,
    check_in    text    NOT NULL,
    check_out   text    NOT NULL,
    guests      integer NOT NULL,
    villa_id    text    NOT NULL,
    group_id    text,
    note        text    NOT NULL,
    status      text    NOT NULL CHECK (status IN ('new', 'contacted', 'converted', 'closed')),
    booking_id  text,
    created_on  text    NOT NULL,
    created_at  text    NOT NULL,
    handled_by  text,
    status_note text    NOT NULL DEFAULT '',
    version     bigint  NOT NULL DEFAULT 1
);

-- Property's catalog, projected from property events: the public site serves it, and listings
-- and enquiries take their villa and location scope from it. version drops a late older event.
CREATE TABLE channel.rm_locations (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    name    text   NOT NULL,
    area    text   NOT NULL,
    version bigint NOT NULL
);

CREATE TABLE channel.rm_villas (
    seq         bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          text   PRIMARY KEY,
    location_id text   NOT NULL,
    code        text   NOT NULL,
    name        text   NOT NULL,
    description text   NOT NULL,
    facilities  text[] NOT NULL,
    version     bigint NOT NULL
);

CREATE TABLE channel.rm_unit_groups (
    seq              bigint  GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id               text    PRIMARY KEY,
    villa_id         text    NOT NULL,
    name             text    NOT NULL,
    interchangeable  boolean NOT NULL,
    operator_assigns boolean NOT NULL,
    version          bigint  NOT NULL
);

CREATE TABLE channel.rm_units (
    seq          bigint  GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id           text    PRIMARY KEY,
    villa_id     text    NOT NULL,
    location_id  text    NOT NULL,
    group_id     text,
    code         text    NOT NULL,
    name         text    NOT NULL,
    bedrooms     integer NOT NULL,
    nightly_rate bigint  NOT NULL,
    status       text    NOT NULL,
    amenities    text[]  NOT NULL,
    version      bigint  NOT NULL
);

CREATE TABLE channel.rm_rate_plans (
    seq          bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    group_id     text   PRIMARY KEY,
    weekday_rate bigint NOT NULL,
    weekend_rate bigint NOT NULL,
    seasons      jsonb  NOT NULL,
    version      bigint NOT NULL
);

CREATE TABLE channel.rm_unit_blocks (
    seq       bigint  GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id        text    PRIMARY KEY,
    unit_id   text    NOT NULL,
    from_date text    NOT NULL,
    to_date   text    NOT NULL,
    removed   boolean NOT NULL DEFAULT false
);

-- Listings with the villa and location of their unit, for scoped reads. A listing whose unit has
-- not been projected yet has no villa; only unrestricted users see it until the unit arrives.
CREATE VIEW channel.v_listings AS
SELECT l.seq, l.id, l.account_id, l.unit_id, l.title, l.airbnb_id, l.status, l.date_rates,
       coalesce(u.villa_id, '') AS villa_id, coalesce(u.location_id, '') AS location_id, u.nightly_rate
FROM channel.listings l
LEFT JOIN channel.rm_units u ON u.id = l.unit_id;

