-- +goose Up
-- Write model. Every record keeps the console's JSON in doc; booking_id, villa_id and location_id
-- carry the stay and the scope a read filters on, ref the other key a rule looks up (the city
-- ledger account, the group, the cashbox). Reads come from these tables directly: billing's own
-- data is consistent at once, and the scope filter needs no join.
CREATE TABLE billing.counters (
    key text   PRIMARY KEY,
    n   bigint NOT NULL
);

CREATE TABLE billing.settings (
    key     text   PRIMARY KEY,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

CREATE TABLE billing.postings (
    seq         bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          text   PRIMARY KEY,
    booking_id  text   NOT NULL DEFAULT '',
    villa_id    text   NOT NULL DEFAULT '',
    location_id text   NOT NULL DEFAULT '',
    ref         text   NOT NULL DEFAULT '',
    doc         jsonb  NOT NULL,
    version     bigint NOT NULL DEFAULT 1
);
CREATE INDEX postings_booking ON billing.postings (booking_id);
CREATE INDEX postings_ref ON billing.postings (ref);

CREATE TABLE billing.payments (LIKE billing.postings INCLUDING ALL);
CREATE TABLE billing.links (LIKE billing.postings INCLUDING ALL);
CREATE TABLE billing.night_audits (LIKE billing.postings INCLUDING ALL);
CREATE TABLE billing.shifts (LIKE billing.postings INCLUDING ALL);
CREATE TABLE billing.hand_overs (LIKE billing.postings INCLUDING ALL);
CREATE TABLE billing.transaction_codes (LIKE billing.postings INCLUDING ALL);
CREATE TABLE billing.cl_accounts (LIKE billing.postings INCLUDING ALL);
CREATE TABLE billing.cl_invoices (LIKE billing.postings INCLUDING ALL);
CREATE TABLE billing.cl_payments (LIKE billing.postings INCLUDING ALL);
CREATE TABLE billing.cl_write_offs (LIKE billing.postings INCLUDING ALL);
-- Finance's cash accounts as the demo seed has them, read by clients.PendingFinance until finance
-- answers CashAccounts.
CREATE TABLE billing.cash_accounts (LIKE billing.postings INCLUDING ALL);

-- The nights the audit posted on each stay, in night order.
CREATE TABLE billing.night_posts (
    booking_id text  PRIMARY KEY,
    dates      jsonb NOT NULL
);

-- Copies of other contexts, kept from their events.
CREATE TABLE billing.rm_stays (
    id          text   PRIMARY KEY,
    code        text   NOT NULL,
    unit_id     text   NOT NULL,
    villa_id    text   NOT NULL DEFAULT '',
    location_id text   NOT NULL DEFAULT '',
    group_id    text   NOT NULL DEFAULT '',
    status      text   NOT NULL,
    doc         jsonb  NOT NULL,
    version     bigint NOT NULL
);
CREATE INDEX rm_stays_group ON billing.rm_stays (group_id);
CREATE INDEX rm_stays_status ON billing.rm_stays (status);

CREATE TABLE billing.rm_groups (
    id      text   PRIMARY KEY,
    doc     jsonb  NOT NULL,
    version bigint NOT NULL
);

CREATE TABLE billing.cat_locations (
    id      text   PRIMARY KEY,
    name    text   NOT NULL,
    version bigint NOT NULL
);

CREATE TABLE billing.cat_villas (
    id          text   PRIMARY KEY,
    location_id text   NOT NULL,
    name        text   NOT NULL,
    version     bigint NOT NULL
);

CREATE TABLE billing.cat_units (
    id       text   PRIMARY KEY,
    villa_id text   NOT NULL,
    code     text   NOT NULL,
    name     text   NOT NULL,
    version  bigint NOT NULL
);

