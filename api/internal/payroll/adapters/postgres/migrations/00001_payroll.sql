-- +goose Up
-- Write model: the settings (one row) and one row per period, each a JSON document with the
-- columns the rules need. version drives optimistic concurrency.
CREATE TABLE payroll.settings (
    id      integer PRIMARY KEY CHECK (id = 1),
    data    jsonb   NOT NULL,
    version bigint  NOT NULL DEFAULT 1
);

CREATE TABLE payroll.periods (
    seq     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id      text   PRIMARY KEY,
    month   text   NOT NULL UNIQUE,
    data    jsonb  NOT NULL,
    version bigint NOT NULL DEFAULT 1
);

-- Numbering as the mock's seq(): adj-.
CREATE TABLE payroll.counters (
    key text    PRIMARY KEY,
    n   integer NOT NULL
);

-- Read models of payroll's own records: views, consistent at once.
CREATE VIEW payroll.v_settings AS SELECT data FROM payroll.settings;
CREATE VIEW payroll.v_periods AS SELECT seq, id, month, data FROM payroll.periods;

-- Copies of the people records a payslip is computed from, projected from people events. Each
-- employee row carries its villas and their locations for the scope filter; version drops an
-- older event that arrives late.
CREATE TABLE payroll.rm_employees (
    seq          bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id           text   PRIMARY KEY,
    villa_ids    text[] NOT NULL,
    location_ids text[] NOT NULL,
    data         jsonb  NOT NULL,
    version      bigint NOT NULL
);

CREATE TABLE payroll.rm_attendance (
    id          text   PRIMARY KEY,
    employee_id text   NOT NULL,
    day         text   NOT NULL,
    data        jsonb  NOT NULL,
    version     bigint NOT NULL
);
CREATE INDEX rm_attendance_day ON payroll.rm_attendance (day);

CREATE TABLE payroll.rm_overtime (
    id          text   PRIMARY KEY,
    employee_id text   NOT NULL,
    day         text   NOT NULL,
    data        jsonb  NOT NULL,
    version     bigint NOT NULL
);
CREATE INDEX rm_overtime_day ON payroll.rm_overtime (day);

CREATE TABLE payroll.rm_loans (
    seq         bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id          text   PRIMARY KEY,
    employee_id text   NOT NULL,
    data        jsonb  NOT NULL,
    version     bigint NOT NULL
);

