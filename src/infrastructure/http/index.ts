import type { Clock, Ports } from '@/application/ports'
import { createHttpClient } from './client'

const BOOKING_ACTION = { confirmed: 'confirm', checked_in: 'check-in', checked_out: 'check-out', cancelled: 'cancel', no_show: 'no-show' } as const
const TRANSACTION_ACTION = { submitted: 'submit', approved: 'approve', rejected: 'reject', posted: 'post' } as const
const PAYROLL_ACTION = { draft: 'reopen', calculated: 'calculate', approved: 'approve', closed: 'close' } as const

/**
 * REST adapters behind the same ports as the mock, on the routes docs/05-api-rules.md lists.
 * Point VITE_API_URL at the Go API (`https://host/api/v1`) and the whole UI runs against it.
 */
export function createHttpPorts(baseUrl: string, clock: Clock): Ports {
  const http = createHttpClient(baseUrl)
  return {
    clock,
    property: {
      locations: () => http.get('locations'),
      villas: () => http.get('villas'),
      units: () => http.get('units'),
      groups: () => http.get('unit-groups'),
      createLocation: (input) => http.post('locations', input),
      updateLocation: (id, input) => http.patch(`locations/${id}`, input),
      createVilla: (input) => http.post('villas', input),
      createProperty: (input) => http.post('properties', input),
      updateVilla: (id, input) => http.patch(`villas/${id}`, input),
      createGroup: (input) => http.post('unit-groups', input),
      updateGroup: (id, input) => http.patch(`unit-groups/${id}`, input),
      createUnit: (input) => http.post('units', input),
      updateUnit: (id, input) => http.patch(`units/${id}`, input),
    },
    airbnb: {
      accounts: () => http.get('airbnb-accounts'),
      listings: () => http.get('airbnb-listings'),
      setListingStatus: (id, status) => http.patch(`airbnb-listings/${id}`, { status }),
      createAccount: (input) => http.post('airbnb-accounts', input),
      updateAccount: (id, input) => http.patch(`airbnb-accounts/${id}`, input),
      createListing: (input) => http.post('airbnb-listings', input),
      updateListing: (id, input) => http.patch(`airbnb-listings/${id}`, input),
    },
    booking: {
      bookings: () => http.get('bookings'),
      blocks: () => http.get('unit-blocks'),
      create: (input) => http.post('bookings', input),
      transition: (id, to) => http.post(`bookings/${id}/${BOOKING_ACTION[to]}`),
      checkIn: (id, details) => http.post(`bookings/${id}/check-in`, details),
      checkOut: (id, details) => http.post(`bookings/${id}/check-out`, details),
      moveUnit: (id, unitId, reason) => http.post(`bookings/${id}/move-unit`, { unitId, reason }),
      adjustStay: (id, checkIn, checkOut) => http.patch(`bookings/${id}`, { checkIn, checkOut }),
      updateNotes: (id, notes) => http.patch(`bookings/${id}`, { notes }),
      setPayment: (id, payment) => http.patch(`bookings/${id}/payment`, payment),
      addBlock: (input) => http.post('unit-blocks', input),
      removeBlock: (id) => http.delete(`unit-blocks/${id}`),
    },
    guest: {
      guests: () => http.get('guests'),
      create: (input) => http.post('guests', input),
      update: (id, input) => http.patch(`guests/${id}`, input),
    },
    finance: {
      accounts: () => http.get('cash-accounts'),
      createAccount: (input) => http.post('cash-accounts', input),
      updateAccount: (id, input) => http.patch(`cash-accounts/${id}`, input),
      categories: () => http.get('categories'),
      transactions: () => http.get('transactions'),
      createTransaction: (input, submit, origin = 'manual') => http.post('transactions', { ...input, submit, origin }),
      transition: (id, to, note = '') => http.post(`transactions/${id}/${TRANSACTION_ACTION[to]}`, { note }),
      reverse: (id, reason) => http.post(`transactions/${id}/reverse`, { reason }),
      transfer: (input) => http.post('transactions/transfers', input),
      adjust: (input) => http.post('transactions/adjustments', input),
      reconciliations: () => http.get('reconciliations'),
      reconcile: (input) => http.post('reconciliations', input),
      createCategory: (input) => http.post('categories', input),
      updateCategory: (id, input) => http.patch(`categories/${id}`, input),
      setCategoryActive: (id, active) => http.patch(`categories/${id}`, { active }),
      approvalRules: () => http.get('approval-rules'),
      createRule: (input) => http.post('approval-rules', input),
      updateRule: (id, input) => http.patch(`approval-rules/${id}`, input),
      deleteRule: (id) => http.delete(`approval-rules/${id}`),
    },
    service: {
      requests: () => http.get('service-requests'),
      create: (input) => http.post('service-requests', input),
      update: (id, input) => http.patch(`service-requests/${id}`, input),
      transition: (id, to) => http.post(`service-requests/${id}/${to === 'in_progress' ? 'start' : to === 'done' ? 'done' : 'cancel'}`),
      assign: (id, assignee) => http.patch(`service-requests/${id}`, { assignee }),
      linkTransaction: (id, transactionId) => http.patch(`service-requests/${id}`, { transactionId }),
    },
    maintenance: {
      workOrders: () => http.get('work-orders'),
      createWorkOrder: (input) => http.post('work-orders', input),
      updateWorkOrder: (id, input) => http.patch(`work-orders/${id}`, input),
      transitionWorkOrder: (id, to, note) => http.post(`work-orders/${id}/status`, { status: to, note }),
      addNote: (id, note) => http.post(`work-orders/${id}/notes`, { note }),
      setBlock: (id, from, to) => http.put(`work-orders/${id}/block`, { from, to }),
      linkTransaction: (id, transactionId) => http.patch(`work-orders/${id}`, { transactionId }),
      assets: () => http.get('assets'),
      createAsset: (input) => http.post('assets', input),
      updateAsset: (id, input) => http.patch(`assets/${id}`, input),
      vendors: () => http.get('vendors'),
      createVendor: (input) => http.post('vendors', input),
      updateVendor: (id, input) => http.patch(`vendors/${id}`, input),
      plans: () => http.get('preventive-plans'),
      createPlan: (input) => http.post('preventive-plans', input),
      updatePlan: (id, input) => http.patch(`preventive-plans/${id}`, input),
      generateDue: (horizonDays) => http.post('preventive-plans/generate', { horizonDays }),
      housekeeping: () => http.get('housekeeping'),
      setHousekeeping: (unitId, state, note) => http.put(`housekeeping/${unitId}`, { state, note }),
      inspect: (unitId, results, raiseWorkOrder) => http.post(`housekeeping/${unitId}/inspections`, { results, raiseWorkOrder }),
    },
    hr: {
      employees: () => http.get('employees'),
      createEmployee: (input) => http.post('employees', input),
      updateEmployee: (id, input) => http.patch(`employees/${id}`, input),
      shifts: () => http.get('shifts'),
      assignments: () => http.get('shift-assignments'),
      assignShift: (input) => http.put('shift-assignments', input),
      attendance: () => http.get('attendance'),
      recordAttendance: (input) => http.put('attendance', input),
      leaves: () => http.get('leave-requests'),
      requestLeave: (input) => http.post('leave-requests', input),
      decideLeave: (id, to, note) => http.post(`leave-requests/${id}/${to === 'approved' ? 'approve' : to === 'rejected' ? 'reject' : 'cancel'}`, { note }),
      overtime: () => http.get('overtime-requests'),
      requestOvertime: (input) => http.post('overtime-requests', input),
      decideOvertime: (id, to, note) => http.post(`overtime-requests/${id}/${to === 'approved' ? 'approve' : to === 'rejected' ? 'reject' : 'cancel'}`, { note }),
      loans: () => http.get('loans'),
      requestLoan: (input) => http.post('loans', input),
      decideLoan: (id, to, note) => http.post(`loans/${id}/${to === 'approved' ? 'approve' : to === 'rejected' ? 'reject' : 'cancel'}`, { note }),
    },
    payroll: {
      settings: () => http.get('payroll/settings'),
      saveSettings: (settings) => http.put('payroll/settings', settings),
      periods: () => http.get('payroll/periods'),
      createPeriod: (month) => http.post('payroll/periods', { month }),
      calculate: (id) => http.post(`payroll/periods/${id}/calculate`),
      addAdjustment: (id, employeeId, input) => http.post(`payroll/periods/${id}/lines/${employeeId}/adjustments`, input),
      removeAdjustment: (id, employeeId, adjustmentId) => http.post(`payroll/periods/${id}/lines/${employeeId}/adjustments/${adjustmentId}/remove`),
      transition: (id, to, note, accountId) => http.post(`payroll/periods/${id}/${PAYROLL_ACTION[to]}`, { note, accountId }),
      publish: (id) => http.post(`payroll/periods/${id}/publish`),
    },
    people: {
      announcements: () => http.get('announcements'),
      createAnnouncement: (input) => http.post('announcements', input),
      updateAnnouncement: (id, input) => http.patch(`announcements/${id}`, input),
      deleteAnnouncement: (id) => http.delete(`announcements/${id}`),
      kpis: () => http.get('kpi-reviews'),
      saveKpi: (id, input) => (id ? http.put(`kpi-reviews/${id}`, input) : http.post('kpi-reviews', input)),
    },
    access: {
      session: () => http.get('auth/session'),
      login: (input) => http.post('auth/login', input),
      logout: () => http.post('auth/logout'),
      changePassword: (input) => http.post('auth/password', input),
      users: () => http.get('users'),
      createUser: (input) => http.post('users', input),
      updateUser: (id, input) => http.patch(`users/${id}`, input),
      setUserActive: (id, active) => http.patch(`users/${id}`, { status: active ? 'active' : 'inactive' }),
      permissions: () => http.get('permissions'),
      savePermissions: (role, perms) => http.put(`permissions/${role}`, perms),
      audit: () => http.get('audit'),
    },
    account: {
      profile: () => http.get('me'),
      saveProfile: (profile) => http.put('me', profile),
    },
  }
}
